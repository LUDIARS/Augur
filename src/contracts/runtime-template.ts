// Contract runtime distribution (spec/tasks/2026-10-13-contract-runtime-template.md).
// Pure: template text in, generated copy or drift verdict out. Every repository
// that carries contract-wrap markers keeps a generated copy of Augur's template
// at `augur.contracts.json#runtime`; the header names the template version and
// the SHA-256 of the body, so a copy edited in place and a copy generated from an
// older template are told apart without diffing against Augur's history.

import { createHash } from 'node:crypto';

/** Bumped when the template's observable rules change (rotation, record shape). */
export const CONTRACT_RUNTIME_TEMPLATE_VERSION = 2;

export type RuntimeFlavor = 'ts' | 'mjs';

export type RuntimeDrift = 'missing' | 'unmanaged' | 'modified' | 'outdated';

export type RuntimeInspection =
  | { readonly state: 'current'; readonly version: number; readonly sha256: string }
  | { readonly state: RuntimeDrift; readonly message: string };

const HEADER_PREFIX = '// augur-contract-runtime';
const HEADER = /^\/\/ augur-contract-runtime version=(\d+) sha256=([0-9a-f]{64})\n/;
const NOTICE = '// Generated by `augur contracts runtime sync` from Augur templates/contract-runtime. Edit the template, then re-sync.\n';

/** `.ts` copies get the typed template; `.mjs` / `.js` get the plain one. */
export function runtimeFlavorOf(path: string): RuntimeFlavor | null {
  if (/\.(?:ts|mts)$/i.test(path)) return 'ts';
  if (/\.(?:mjs|js)$/i.test(path)) return 'mjs';
  return null;
}

/** Line endings are normalized so a checkout with autocrlf hashes the same. */
function body(text: string): string {
  return text.replace(/\r\n/g, '\n');
}

export function runtimeBodyHash(text: string): string {
  return createHash('sha256').update(body(text), 'utf8').digest('hex');
}

/** @implements SPEC-CONTRACT-RUNTIME-TEMPLATE */
export function renderContractRuntime(template: string): string {
  const content = body(template);
  return `${HEADER_PREFIX} version=${CONTRACT_RUNTIME_TEMPLATE_VERSION} sha256=${runtimeBodyHash(content)}\n${NOTICE}${content}`;
}

/**
 * `existing` undefined means the file is absent.
 * @implements SPEC-CONTRACT-RUNTIME-TEMPLATE
 */
export function inspectContractRuntime(existing: string | undefined, template: string): RuntimeInspection {
  if (existing === undefined) return { state: 'missing', message: 'runtime file not found; run `augur contracts runtime sync`' };
  const text = body(existing);
  const header = HEADER.exec(text);
  if (header === null) {
    return { state: 'unmanaged', message: 'runtime file has no augur-contract-runtime header (hand-written copy)' };
  }
  const rest = text.slice(header[0].length);
  const content = rest.startsWith(NOTICE) ? rest.slice(NOTICE.length) : rest;
  const version = Number(header[1]);
  const recorded = header[2]!;
  if (runtimeBodyHash(content) !== recorded) {
    return { state: 'modified', message: 'runtime file was edited after generation; change the Augur template instead' };
  }
  const expected = runtimeBodyHash(template);
  if (version !== CONTRACT_RUNTIME_TEMPLATE_VERSION || recorded !== expected) {
    return {
      state: 'outdated',
      message: `runtime file was generated from template version ${version}; current is ${CONTRACT_RUNTIME_TEMPLATE_VERSION}`,
    };
  }
  return { state: 'current', version, sha256: recorded };
}
